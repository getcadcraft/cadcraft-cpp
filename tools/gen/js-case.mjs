// Writes libs/base/src/js_case.inc: every code point whose String#toUpperCase / #toLowerCase differs from itself, as
// the running Node (its ICU) maps it, so cc::base::js_to_upper / js_to_lower give what the 0.5 JS gives. Unicode data,
// not code: regenerate when the Unicode version moves (node tools/gen/js-case.mjs).
import { writeFileSync } from 'node:fs';
const up = [], lo = [];
for (let cp = 0; cp < 0x110000; cp++) {
  if (cp >= 0xd800 && cp < 0xe000) continue;
  const s = String.fromCodePoint(cp);
  const u = [...s.toUpperCase()].map((c) => c.codePointAt(0)), l = [...s.toLowerCase()].map((c) => c.codePointAt(0));
  if (s.toUpperCase() !== s) up.push([cp, ...u]);
  if (s.toLowerCase() !== s) lo.push([cp, ...l]);
}
const max = Math.max(...up.map((r) => r.length - 1), ...lo.map((r) => r.length - 1));
if (max > 3) throw new Error('a mapping longer than 3 code points');
const row = (r) => `{0x${r[0].toString(16)}, {${r.slice(1).map((c) => '0x' + c.toString(16)).join(', ')}}}`;
const out = `// SPDX-License-Identifier: Apache-2.0
// Generated by tools/gen/js-case.mjs from Node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}): do not edit.
// {code point, {its upper / lower case, up to three code points}}, sorted by code point.
// clang-format off
inline constexpr std::array<CaseMap, ${up.length}> kUpper = {{
${up.map(row).join(',\n')}
}};
inline constexpr std::array<CaseMap, ${lo.length}> kLower = {{
${lo.map(row).join(',\n')}
}};
// clang-format on
`;
writeFileSync(new URL('../../libs/base/src/js_case.inc', import.meta.url), out);
console.log(`${up.length} upper, ${lo.length} lower mappings`);
