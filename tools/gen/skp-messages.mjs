// Writes libs/io-skp/src/messages.inc: cc-skp's English (lib/skp/messages.js MESSAGES of the frozen CadCraft 0.5,
// $FORK_PARITY_JS), so every error and note the port says reads exactly as the JS says it.
//   node tools/gen/skp-messages.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.env.FORK_PARITY_JS || join(process.env.CADCRAFT_TESTFILES || '/var/www/CADCRAFT/testfiles', 'fork-parity/js-0.5');
const { MESSAGES } = await import(pathToFileURL(join(root, 'lib/skp/messages.js')).href);
const lit = (s) => JSON.stringify(s);  // ASCII-safe for these strings: checked below
const rows = [];
for (const [key, v] of Object.entries(MESSAGES)) {
  const one = typeof v === 'string' ? v : v.one;
  const other = typeof v === 'string' ? v : v.other;
  for (const s of [key, one, other]) if (/[^\x20-\x7e]/.test(s)) throw new Error('non-ASCII message: ' + key);
  const keys = typeof v === 'object' ? Object.keys(v).filter((k) => k !== 'one' && k !== 'other') : [];
  if (keys.length) throw new Error('a plural form the port does not know: ' + key + ' ' + keys);
  rows.push(`    {${lit(key)}, ${typeof v === 'string' ? 'false' : 'true'}, ${lit(one)}, ${lit(other)}}`);
}
const out = `// SPDX-License-Identifier: Apache-2.0
// Generated by tools/gen/skp-messages.mjs from CadCraft 0.5's lib/skp/messages.js: do not edit.
// {key, plural, one (or the text), other}, in the JS table's order.
// clang-format off
inline constexpr std::array<Message, ${rows.length}> kMessages = {{
${rows.join(',\n')},
}};
// clang-format on
`;
writeFileSync(new URL('../../libs/io-skp/src/messages.inc', import.meta.url), out);
console.log(rows.length + ' messages');
