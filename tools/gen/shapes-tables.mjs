// Writes libs/shapes/src/sections_data.inc and parts_data.inc: the rows of CadCraft 0.5's lib/shapes/sections.js and
// parts.js (published standard tables: dimensions are facts), each number as the JS evaluates it (shortest round-trip
// text, so `7 / 16` becomes the same double), so cc::shapes builds the same records. Data, not code: regenerate only
// from a frozen JS copy (node tools/gen/shapes-tables.mjs; FORK_PARITY_JS points at it).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const testfiles = process.env.CADCRAFT_TESTFILES || '/var/www/CADCRAFT/testfiles';
const js05 = process.env.FORK_PARITY_JS || join(testfiles, 'fork-parity/js-0.5');
const lib = join(js05, 'lib/shapes');

// `const NAME = [ … ];` at the top level, evaluated on its own (the tables are plain literals)
function tables(src, names) {
  const out = {};
  for (const n of names) {
    const m = new RegExp(`^const ${n} = (\\[.*\\]);$`, 'm').exec(src) || new RegExp(`^const ${n} = (\\[[\\s\\S]*?\\n\\]);`, 'm').exec(src);
    if (!m) throw new Error('table ' + n + ' not found');
    out[n] = Function('"use strict"; return ' + m[1])();
  }
  return out;
}
const num = (v) => {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error('not a finite number: ' + v);
  const s = String(v);
  return /[.e]/.test(s) ? s : s + '.0';
};
const str = (s) => JSON.stringify(s);
const row = (r) => (typeof r[0] === 'string' ? '{' + str(r[0]) + ', {' + r.slice(1).map(num).join(', ') + '}}' : '{' + r.map(num).join(', ') + '}');
const head = (what) => `// SPDX-License-Identifier: Apache-2.0
// Generated by tools/gen/shapes-tables.mjs from CadCraft 0.5's lib/shapes/${what}: do not edit.
// clang-format off
// NOLINTBEGIN(modernize-use-std-numbers): published table values, not constants
`;

const S = readFileSync(join(lib, 'sections.js'), 'utf8');
const ST = tables(S, ['AISC_W', 'AISC_S', 'AISC_C', 'AISC_L', 'AISC_L2', 'AISC_RHS', 'AISC_CHS', 'AISC_PIPE', 'EN_I', 'EN_UPN']);
let sec = head('sections.js');
for (const [n, rows] of Object.entries(ST)) {
  const w = rows[0].length - 1;
  sec += `inline constexpr std::array<SecRow<${w}>, ${rows.length}> k${n} = {{\n${rows.map(row).join(',\n')}\n}};\n`;
}
sec += '// NOLINTEND(modernize-use-std-numbers)\n// clang-format on\n';
writeFileSync(new URL('../../libs/shapes/src/sections_data.inc', import.meta.url), sec);

const P = readFileSync(join(lib, 'parts.js'), 'utf8');
const PT = tables(P, ['METRIC', 'INCH', 'PINS', 'BEARINGS', 'KEYS', 'MODULES', 'R_LENGTHS', 'KEY_LENGTHS', 'INCH_LENGTHS']);
let par = head('parts.js');
par += `inline constexpr std::array<MetricRow, ${PT.METRIC.length}> kMetric = {{\n${PT.METRIC.map(row).join(',\n')}\n}};\n`;
par += `inline constexpr std::array<InchRow, ${PT.INCH.length}> kInch = {{\n${PT.INCH.map(row).join(',\n')}\n}};\n`;
par += `inline constexpr std::array<std::array<double, 2>, ${PT.PINS.length}> kPins = {{\n${PT.PINS.map(row).join(',\n')}\n}};\n`;
par += `inline constexpr std::array<BearingRow, ${PT.BEARINGS.length}> kBearings = {{\n${PT.BEARINGS.map(row).join(',\n')}\n}};\n`;
par += `inline constexpr std::array<std::array<double, 6>, ${PT.KEYS.length}> kKeys = {{\n${PT.KEYS.map(row).join(',\n')}\n}};\n`;
for (const [n, k] of [['MODULES', 'kModules'], ['R_LENGTHS', 'kRLengths'], ['KEY_LENGTHS', 'kKeyLengths'], ['INCH_LENGTHS', 'kInchLengths']]) {
  par += `inline constexpr std::array<double, ${PT[n].length}> ${k} = {${PT[n].map(num).join(', ')}};\n`;
}
par += '// NOLINTEND(modernize-use-std-numbers)\n// clang-format on\n';
writeFileSync(new URL('../../libs/shapes/src/parts_data.inc', import.meta.url), par);
