#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
// Writes libs/base/src/js_collation.inc: how Node's ICU root collation (`localeCompare(b, undefined, { numeric: true })`)
// orders the characters a drawing's names hold — ASCII and every character a Windows-1252 file can carry (U+00A0–U+024F
// and the 1252 extras) — measured, not assumed:
//   symbols (punctuation, signs, currency): one primary rank each, in ICU's order (equal at base strength = same rank);
//   letter-like characters: the ASCII letters they sort as (™ → "tm", ß → "ss", ª → "a"), an accent rank and a case rank.
// Unicode data, not code: regenerate when Node's ICU moves (node tools/gen/js-collation.mjs).
import { writeFileSync } from 'node:fs';

const base = new Intl.Collator(undefined, { sensitivity: 'base', numeric: true });
const accent = new Intl.Collator(undefined, { sensitivity: 'accent', numeric: true });
const full = new Intl.Collator(undefined, { numeric: true });

const targets = [];
for (let cp = 0x21; cp < 0x7f; cp++) targets.push(cp);
for (let cp = 0xa0; cp <= 0x24f; cp++) targets.push(cp);
for (const cp of [0x152, 0x153, 0x160, 0x161, 0x178, 0x17d, 0x17e, 0x192, 0x2c6, 0x2dc, 0x2013, 0x2014, 0x2018, 0x2019, 0x201a,
  0x201c, 0x201d, 0x201e, 0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2039, 0x203a, 0x20ac, 0x2122]) if (!targets.includes(cp)) targets.push(cp);

// candidate letter spellings: a–z, then two letters (æ → ae, ™ → tm, ß → ss)
const letters = 'abcdefghijklmnopqrstuvwxyz';
const cands = [...letters];
for (const a of letters) for (const b of letters) cands.push(a + b);

const sym = [], let_ = [];
for (const cp of targets) {
  const ch = String.fromCodePoint(cp);
  if (/[0-9]/.test(ch)) continue;  // digits: numeric runs, handled in code
  if (base.compare(ch, '') === 0) { let_.push({ cp, exp: '', ignorable: true }); continue; }
  const exp = cands.find((c) => base.compare(ch, c) === 0);
  if (exp !== undefined) let_.push({ cp, exp });
  else sym.push(cp);
}
// symbols in ICU order; equal at base strength → one rank
sym.sort((a, b) => full.compare(String.fromCodePoint(a), String.fromCodePoint(b)));
const symRank = new Map();
let rank = 0;
for (let i = 0; i < sym.length; i++) {
  if (i > 0 && base.compare(String.fromCodePoint(sym[i - 1]), String.fromCodePoint(sym[i])) !== 0) rank++;
  symRank.set(sym[i], rank + 1);
}
// letters: accent and case ranks among the characters with the same spelling
const groups = new Map();
for (const l of let_) { if (!groups.has(l.exp)) groups.set(l.exp, []); groups.get(l.exp).push(l); }
for (const [exp, g] of groups) {
  const all = [...g.map((l) => l.cp)];
  // include the plain spelling itself so its accent rank is 0
  const plainStr = exp, items = all.map((cp) => String.fromCodePoint(cp));
  const sorted = [plainStr, ...items].filter((v, i, a) => a.indexOf(v) === i).sort((a, b) => full.compare(a, b));
  let ar = 0;
  const accentOf = new Map();
  for (let i = 0; i < sorted.length; i++) {
    if (i > 0 && accent.compare(sorted[i - 1], sorted[i]) !== 0) ar++;
    accentOf.set(sorted[i], ar);
  }
  const plainAccent = accentOf.get(plainStr) ?? 0;
  // tertiary (case and variant) rank among those equal at the accent level, in ICU's order
  const tertOf = new Map();
  for (let i = 0, t = 0; i < sorted.length; i++) {
    t = i > 0 && accent.compare(sorted[i - 1], sorted[i]) === 0 ? t + 1 : 0;
    tertOf.set(sorted[i], t);
  }
  const plainTert = tertOf.get(plainStr) ?? 0;
  for (const l of g) {
    const s = String.fromCodePoint(l.cp);
    l.accent = (accentOf.get(s) ?? 0) - plainAccent + 64;   // 64 = the plain letters' accent weight
    l.upper = (tertOf.get(s) ?? 0) - (accentOf.get(s) === plainAccent ? plainTert : 0);
  }
}
const rows = [];
for (const cp of targets) {
  if (/[0-9]/.test(String.fromCodePoint(cp))) continue;
  if (symRank.has(cp)) rows.push({ cp, kind: 0, primary: symRank.get(cp), exp: '', accent: 0, upper: 0 });
  else {
    const l = let_.find((x) => x.cp === cp);
    rows.push({ cp, kind: l.ignorable ? 2 : 1, primary: 0, exp: l.exp, accent: l.accent ?? 64, upper: l.upper ?? 0 });
  }
}
rows.sort((a, b) => a.cp - b.cp);
const q = (s) => `"${s}"`;
const out = `// SPDX-License-Identifier: Apache-2.0
// Generated by tools/gen/js-collation.mjs from Node ${process.version} (ICU ${process.versions.icu}): do not edit.
// {code point, kind (0 symbol, 1 letter-like, 2 ignorable), symbol rank, ASCII letters it sorts as, accent, tertiary}
// clang-format off
inline constexpr std::array<Collation, ${rows.length}> kCollation = {{
${rows.map((r) => `{0x${r.cp.toString(16)}, ${r.kind}, ${r.primary}, ${q(r.exp)}, ${r.accent}, ${r.upper}}`).join(',\n')}
}};
inline constexpr std::uint32_t kSymbolRanks = ${rank + 1};
// clang-format on
`;
writeFileSync(new URL('../../libs/base/src/js_collation.inc', import.meta.url), out);
console.log(`${rows.length} characters: ${sym.length} symbols in ${rank + 1} ranks, ${let_.length} letter-like`);
