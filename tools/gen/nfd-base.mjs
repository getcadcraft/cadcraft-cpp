// Writes libs/partcraft/src/nfd_base.inc: every code point above U+007F whose NFD form starts with a printable ASCII
// character, as the running Node (its ICU) decomposes it, so font.js charAdvance's `ch.normalize('NFD')[0]` can be
// answered without a normalizer. Unicode data, not code: regenerate when the Unicode version moves
// (node tools/gen/nfd-base.mjs).
import { writeFileSync } from 'node:fs';
const rows = [];
for (let cp = 0x80; cp < 0x110000; cp++) {
  if (cp >= 0xd800 && cp < 0xe000) continue;
  const b = String.fromCodePoint(cp).normalize('NFD').charCodeAt(0);
  if (b >= 32 && b < 127) rows.push([cp, b]);
}
const out = `// SPDX-License-Identifier: Apache-2.0
// Generated by tools/gen/nfd-base.mjs from Node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}): do not edit.
// {code point, the printable ASCII character its NFD form starts with}, sorted by code point.
// clang-format off
inline constexpr std::array<std::array<std::uint32_t, 2>, ${rows.length}> kNfdBase = {{
${rows.map(([c, b]) => `{0x${c.toString(16)}, 0x${b.toString(16)}}`).join(',\n')}
}};
// clang-format on
`;
writeFileSync(new URL('../../libs/partcraft/src/nfd_base.inc', import.meta.url), out);
